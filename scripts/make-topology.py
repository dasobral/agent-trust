#!/usr/bin/env python3
"""Prints a scale topology with N agents: scripts/make-topology.py N [--source qrng|os|mock]."""
import argparse

parser = argparse.ArgumentParser()
parser.add_argument("count", type=int)
parser.add_argument("--source", default="qrng", choices=["os", "mock", "qrng"])
args = parser.parse_args()
names = [f"agent{i:02d}" for i in range(1, args.count + 1)]
print(f'# {args.count} agents in one group (generated by scripts/make-topology.py).')
print(f'name = "scale-{args.count}"\ngroup = "scale"\nroot = "{names[0]}"\n')
print(f'[entropy]\nsource = "{args.source}"\n\n[relay]\nseed = 5')
for name in names:
    print(f'\n[[agent]]\nname = "{name}"')
